#!/usr/bin/env python3
"""
Build dist/rx-studio.html: a single self-contained file that runs offline.

prescription.html loads pdf.js, jsPDF and Google Fonts from the internet. This script
inlines all of them (scripts, the pdf.js worker and the woff2 fonts as data URIs) so the
result can be opened by double-clicking it, emailed, or hosted anywhere, with no network.

    cd tests && npm install && cd ..
    python3 tools/build-standalone.py

The library files are read from tests/node_modules, pinned to the same versions the page uses.
"""
import base64
import pathlib
import re
import sys

ROOT = pathlib.Path(__file__).resolve().parent.parent
NM = ROOT / "tests" / "node_modules"
SRC = ROOT / "prescription.html"
OUT = ROOT / "dist" / "rx-studio.html"

LIBS = {
    "pdf.min.js": ("pdfjs-dist/build/pdf.min.js", "pdf.js 3.11.174 · Apache-2.0 · Mozilla"),
    "jspdf.umd.min.js": ("jspdf/dist/jspdf.umd.min.js", "jsPDF 2.5.1 · MIT · James Hall, yWorks"),
}
WORKER = ("pdfjs-dist/build/pdf.worker.min.js", "pdf.js worker 3.11.174 · Apache-2.0 · Mozilla")
FONTS = [  # family, weight, style, file
    *[("IBM Plex Sans", w, "normal", f"ibm-plex-sans/files/ibm-plex-sans-latin-{w}-normal.woff2") for w in (400, 500, 600, 700)],
    ("IBM Plex Sans", 400, "italic", "ibm-plex-sans/files/ibm-plex-sans-latin-400-italic.woff2"),
    *[("IBM Plex Mono", w, "normal", f"ibm-plex-mono/files/ibm-plex-mono-latin-{w}-normal.woff2") for w in (400, 500, 600)],
    *[("Fraunces", w, "normal", f"fraunces/files/fraunces-latin-{w}-normal.woff2") for w in (500, 600)],
]


def read_lib(rel):
    f = NM / rel
    if not f.exists():
        sys.exit(f"Missing {f}. Run: cd tests && npm install")
    code = f.read_text(encoding="utf-8")
    # an inline <script> ends at the first "</script"; the libraries have none today, but stay safe
    return code.replace("</script", "<\\/script").replace("<!--", "<\\!--")


def main():
    html = SRC.read_text(encoding="utf-8")

    # 1. scripts
    for name, (rel, notice) in LIBS.items():
        pat = re.compile(r'<script src="https://cdnjs\.cloudflare\.com/[^"]*/' + re.escape(name) + r'"></script>')
        if not pat.search(html):
            sys.exit(f"Could not find the CDN tag for {name} in prescription.html")
        repl = f"<script>/*! {notice} */\n{read_lib(rel)}\n</script>"
        if name == "pdf.min.js":
            # Loading the worker as a normal script defines window.pdfjsWorker; pdf.js then parses
            # PDFs on the main thread, which needs no worker URL and therefore works from file://.
            repl += f"\n<script>/*! {WORKER[1]} */\n{read_lib(WORKER[0])}\n</script>"
        html = pat.sub(lambda _m, r=repl: r, html, count=1)

    # 2. fonts
    faces = []
    for family, weight, style, rel in FONTS:
        f = NM / "@fontsource" / rel
        if not f.exists():
            sys.exit(f"Missing {f}. Run: cd tests && npm install")
        b64 = base64.b64encode(f.read_bytes()).decode()
        faces.append(f"@font-face{{font-family:'{family}';font-style:{style};font-weight:{weight};font-display:swap;"
                     f"src:url(data:font/woff2;base64,{b64}) format('woff2');}}")
    font_css = "<style>/*! IBM Plex Sans, IBM Plex Mono, Fraunces · SIL Open Font License 1.1 */\n" + "\n".join(faces) + "\n</style>"
    html, n = re.subn(r'<link rel="preconnect" href="https://fonts\.googleapis\.com" />\s*'
                      r'<link rel="preconnect" href="https://fonts\.gstatic\.com" crossorigin />\s*'
                      r'<link href="https://fonts\.googleapis\.com/css2[^"]*" rel="stylesheet" />',
                      lambda _m: font_css, html, count=1)
    if n != 1:
        sys.exit("Could not find the Google Fonts tags in prescription.html")

    if "cdnjs.cloudflare.com/ajax/libs/pdf.js/3.11.174/pdf.worker.min.js" not in html:
        sys.exit("Expected worker fallback URL in app code")  # sanity: app code is untouched
    html = html.replace("<title>Rx Studio · Mediseller</title>",
                        "<title>Rx Studio · Mediseller</title>\n<!-- Standalone build of prescription.html, generated by tools/build-standalone.py. Do not edit by hand. -->", 1)

    OUT.parent.mkdir(exist_ok=True)
    OUT.write_text(html, encoding="utf-8")
    print(f"Wrote {OUT.relative_to(ROOT)} ({OUT.stat().st_size / 1024:.0f} KB)")


if __name__ == "__main__":
    main()
